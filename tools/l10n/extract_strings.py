#!/usr/bin/env python3
"""Extracts the player-visible strings of the game into a gettext template (a POT file).

    python3 tools/l10n/extract_strings.py game > game/locale/messages.pot
    python3 tools/l10n/extract_strings.py game --check game/locale/messages.pot

Sources: the literal `tr("...")`, `tr("...", "context")` and `_translator.tr(...)` calls of the
`*.gd` scripts, and the `text = "..."` properties of the `*.tscn` scenes. The directories `addons`,
`test`, `tools` and `spike` are skipped. A `tr()` call whose message is not a plain string literal
(a variable, a concatenation) cannot be extracted, so it is an error: write the literal instead.

The output is sorted by (context, message) and carries no source line numbers, so it only changes
when a string does. With `--check POT`, the script writes nothing and exits 1 when POT differs from a
fresh extraction.
"""

import argparse
import re
import sys
from pathlib import Path
from typing import NamedTuple

# android/ holds Godot's Gradle build template (make android-template), whose sample scripts are not ours.
SKIPPED_DIRECTORIES = {"addons", "test", "tools", "spike", "android"}

_STRING = r'"((?:[^"\\]|\\.)*)"'
# `tr(` as a call: not the tail of another name (`str(`), optionally on an object (`_translator.tr(`).
_CALL_START = re.compile(r"(?<![\w.])(?:[A-Za-z_]\w*\.)?tr\(")
_CALL = re.compile(r"\s*" + _STRING + r"\s*(?:,\s*" + _STRING + r"\s*)?[,)]", re.DOTALL)
_SCENE_TEXT = re.compile(r"^text = " + _STRING, re.MULTILINE)
_COMMENT_LINE = re.compile(r"^[ \t]*#.*$", re.MULTILINE)
_ESCAPE = re.compile(r"\\(u[0-9a-fA-F]{4}|.)", re.DOTALL)
_SIMPLE_ESCAPES = {"n": "\n", "t": "\t", "r": "\r"}

HEADER = (
    '# Chess Roguelike translation template.\n'
    '# Generated by tools/l10n/extract_strings.py. Do not edit; run make pot.\n'
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: Chess Roguelike\\n"\n'
    '"MIME-Version: 1.0\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
)


class ExtractError(Exception):
    """A string that the extractor cannot see."""


class Entry(NamedTuple):
    context: str
    message: str


def _unescape(literal: str) -> str:
    def replace(match: re.Match) -> str:
        code = match.group(1)
        if code.startswith("u") and len(code) == 5:
            return chr(int(code[1:], 16))
        return _SIMPLE_ESCAPES.get(code, code)

    return _ESCAPE.sub(replace, literal)


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def _script_entries(path: Path, text: str) -> list[Entry]:
    text = _COMMENT_LINE.sub("", text)
    entries = []
    for start in _CALL_START.finditer(text):
        call = _CALL.match(text, start.end())
        if call is None:
            raise ExtractError(
                f"{path}:{_line_of(text, start.start())}: tr() takes a string literal, "
                "which the extractor cannot read here"
            )
        message, context = call.group(1), call.group(2) or ""
        entries.append(Entry(_unescape(context), _unescape(message)))
    return entries


def _scene_entries(text: str) -> list[Entry]:
    return [Entry("", _unescape(m.group(1))) for m in _SCENE_TEXT.finditer(text)]


def extract(root: Path) -> list[Entry]:
    """The entries of every script and scene under `root`, sorted and without duplicates."""
    found = set()
    for path in sorted(root.rglob("*")):
        if not path.is_file() or SKIPPED_DIRECTORIES & set(path.relative_to(root).parts[:-1]):
            continue
        if path.suffix == ".gd":
            found.update(_script_entries(path, path.read_text(encoding="utf-8")))
        elif path.suffix == ".tscn":
            found.update(_scene_entries(path.read_text(encoding="utf-8")))
    return sorted(e for e in found if e.message)


def render_pot(entries: list[Entry]) -> str:
    parts = [HEADER]
    for entry in entries:
        block = ""
        if entry.context:
            block += f'msgctxt "{_escape(entry.context)}"\n'
        block += f'msgid "{_escape(entry.message)}"\nmsgstr ""\n'
        parts.append(block)
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("root", type=Path, help="the Godot project directory")
    parser.add_argument("--check", type=Path, metavar="POT", help="exit 1 when POT is stale")
    args = parser.parse_args(argv)
    try:
        pot = render_pot(extract(args.root))
    except ExtractError as error:
        print(error, file=sys.stderr)
        return 1
    if args.check is None:
        sys.stdout.write(pot)
        return 0
    if not args.check.is_file() or args.check.read_text(encoding="utf-8") != pot:
        print(f"{args.check} is stale: run `make pot`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
